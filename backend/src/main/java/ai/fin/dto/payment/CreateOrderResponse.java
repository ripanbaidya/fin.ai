package ai.fin.dto.payment;

import io.swagger.v3.oas.annotations.media.Schema;

@Schema(description = "Response payload containing payment order details")
public record CreateOrderResponse(

        @Schema(
                description = "Unique payment order ID generated by the payment provider",
                example = "order_NX123456789"
        )
        String orderId,

        @Schema(
                description = "Total order amount in the smallest currency unit (paise for INR)",
                example = "49900"
        )
        long amountInPaise,

        @Schema(
                description = "Three-letter ISO 4217 currency code",
                example = "INR"
        )
        String currency,

        @Schema(
                description = "Public payment provider key ID used by the frontend to initialize checkout",
                example = "rzp_test_abc123xyz"
        )
        String keyId
) {
}