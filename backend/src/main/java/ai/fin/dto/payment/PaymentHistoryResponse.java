package ai.fin.dto.payment;

import ai.fin.enums.PaymentProvider;
import ai.fin.enums.PaymentStatus;
import ai.fin.enums.SubscriptionPlan;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.Instant;

@Schema(description = "Payment history details for a subscription payment")
public record PaymentHistoryResponse(

        @Schema(
                description = "Unique identifier of the payment record",
                example = "pay_123456789"
        )
        String id,

        @Schema(
                description = "Subscription plan associated with the payment",
                example = "MONTHLY"
        )
        SubscriptionPlan plan,

        @Schema(
                description = "Payment provider used to process the transaction",
                example = "RAZORPAY"
        )
        PaymentProvider provider,

        @Schema(
                description = "Order ID generated by the payment provider",
                example = "order_NX123456789"
        )
        String providerOrderId,

        @Schema(
                description = "Payment ID generated by the payment provider; null if payment has not been completed",
                example = "pay_NX987654321",
                nullable = true
        )
        String providerPaymentId,

        @Schema(
                description = "Payment amount in the smallest currency unit (paise for INR)",
                example = "49900"
        )
        long amountInPaise,

        @Schema(
                description = "Three-letter ISO 4217 currency code",
                example = "INR"
        )
        String currency,

        @Schema(
                description = "Current status of the payment",
                example = "CREATED"
        )
        PaymentStatus status,

        @Schema(
                description = "Timestamp when the payment record was created, in ISO 8601 UTC format",
                example = "2026-10-17T10:30:00Z",
                type = "string",
                format = "date-time"
        )
        Instant createdAt
) {
}